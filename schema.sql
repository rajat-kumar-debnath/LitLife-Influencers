-- ----------------------------------------------------------------------
-- Table
-- ----------------------------------------------------------------------
create table if not exists public.influencers (
    id          bigint generated by default as identity primary key,
    handle      text not null unique,
    name        text not null default '',
    category    text not null default '',
    followers   integer,
    email       text not null default '',
    rate        integer,
    status      text not null default 'New'
                check (status in ('New','Contacted','Negotiating','Confirmed','Posted','Rejected')),
    notes       text not null default '',
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create index if not exists idx_influencers_status   on public.influencers (status);
create index if not exists idx_influencers_category on public.influencers (category);

-- ----------------------------------------------------------------------
-- Keep updated_at current on every UPDATE
-- ----------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

drop trigger if exists trg_influencers_touch on public.influencers;
create trigger trg_influencers_touch
    before update on public.influencers
    for each row execute function public.touch_updated_at();

-- ----------------------------------------------------------------------
-- Row Level Security
-- ----------------------------------------------------------------------
-- The anon key in the browser is PUBLIC. RLS decides what that key may do.
--
-- The policy below lets ANYONE who can open the page read AND write the
-- table. That is fine for a personal / internal tool, but means anyone
-- with the URL could edit or delete rows. For a locked-down version,
-- see the "Lock it down" section in README.md (require login, then scope
-- the policy to authenticated users).
alter table public.influencers enable row level security;

drop policy if exists "public read"  on public.influencers;
drop policy if exists "public write" on public.influencers;

create policy "public read"
    on public.influencers for select
    using (true);

create policy "public write"
    on public.influencers for all
    using (true)
    with check (true);

